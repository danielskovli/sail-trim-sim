export const STRINGS = { en, nb };

let current = 'en';
export const getLanguage = () => current;
export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'en';
  return current;
}
export const localeOf = (lang = current) => (LANGS.find((l) => l.id === lang) ?? LANGS[0]).locale;

/** Translate `key` in the current language, interpolating {params}. Unknown keys return the key itself. */
export function t(key, params) {
  return tIn(current, key, params);
}
export function tIn(lang, key, params) {
  const s = STRINGS[lang]?.[key] ?? en[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : m));
}
export const lc = (s) => (typeof s === 'string' && s.length ? s.charAt(0).toLowerCase() + s.slice(1) : s);
export const uc = (s) => (typeof s === 'string' && s.length ? s.charAt(0).toUpperCase() + s.slice(1) : s);

/** Format a number in the current locale (decimal comma in Norwegian). */
export function nf(value, digits = 0) {
  if (!Number.isFinite(value)) return String(value);
  return new Intl.NumberFormat(localeOf(), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value);
}
/** Knots: one decimal below 10, none above. */
export const nfKn = (v) => nf(v, v < 10 ? 1 : 0);
export const fmt3 = (d) => String(Math.round(((d % 360) + 360) % 360)).padStart(3, '0');

/** Pick the initial language: ?lang= in the URL, then a saved choice, then the browser language. */
export function detectLanguage(search = '', saved = null, navigatorLanguage = '') {
  const q = new URLSearchParams(search).get('lang');
  if (q && STRINGS[q]) return q;
  if (saved && STRINGS[saved]) return saved;
  const nav = String(navigatorLanguage).toLowerCase();
  if (nav.startsWith('nb') || nav.startsWith('no') || nav.startsWith('nn')) return 'nb';
  return 'en';
}

/** Apply translations to static markup: `data-i18n` sets textContent, `data-i18n-html` sets innerHTML. */
export function applyStaticTranslations(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.getAttribute('data-i18n'));
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.getAttribute('data-i18n-html'));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
}

